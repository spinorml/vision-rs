    // ── Dimensions ────────────────────────────────────────────────────────────────
    const BATCH:     usize = 2;
    const C1:        usize = 256;
    const C:         usize = 128;
    const H:         usize = 4;
    const W:         usize = 4;

    const NUM_HEADS: usize = 2;
    const HEAD_DIM:  usize = 64;
    const KEY_DIM:   usize = 32;
    const QKV_H:     usize = 256;
    const HEAD_SPAN: usize = 2 * KEY_DIM + HEAD_DIM;
    const SCALE:     f32   = 0.176_776_7_f32;
    const N:         usize = H * W;
    const N_SPATIAL: usize = BATCH * N;

    const BH:              usize = BATCH * NUM_HEADS;
    const FA2_TENSOR_SIZE: usize = BH * N * KEY_DIM;
    const FA2_L_SIZE:      usize = BH * N;

    const BUF_256: usize = N_SPATIAL * C1;
    const BUF_128: usize = N_SPATIAL * C;

    // ── Kernel tuning ─────────────────────────────────────────────────────────────
    const BLOCK_OW:   i32 = 4;
    const BLOCK_BN:   i32 = 128;
    const BLOCK_SILU: i32 = 128;
    const BLOCK_CH:   i32 = 128;
    const BLOCK_VADD: i32 = 128;

    // ── Fixture loader ────────────────────────────────────────────────────────────

    fn load(name: &str) -> Vec<f32> {
        let path = format!(
            "{}/tests/fixtures/c2psa_yolo26/backward/{}",
            env!("CARGO_MANIFEST_DIR"),
            name
        );
        let bytes = std::fs::read(&path)
            .unwrap_or_else(|e| panic!("missing fixture {path}: {e}"));
        bytes
            .chunks_exact(4)
            .map(|b| f32::from_le_bytes([b[0], b[1], b[2], b[3]]))
            .collect()
    }

    // ── Layout helpers ────────────────────────────────────────────────────────────

    fn nchw_to_nc(src: &[f32], b: usize, c: usize, h: usize, w: usize) -> Vec<f32> {
        let mut out = vec![0.0f32; b * h * w * c];
        for bi in 0..b {
            for ci in 0..c {
                for hi in 0..h {
                    for wi in 0..w {
                        let ni = bi * h * w + hi * w + wi;
                        out[ni * c + ci] = src[bi * c * h * w + ci * h * w + hi * w + wi];
                    }
                }
            }
        }
        out
    }

    fn nc_to_nchw(src: &[f32], b: usize, c: usize, h: usize, w: usize) -> Vec<f32> {
        let mut out = vec![0.0f32; b * c * h * w];
        for bi in 0..b {
            for ci in 0..c {
                for hi in 0..h {
                    for wi in 0..w {
                        let ni = bi * h * w + hi * w + wi;
                        out[bi * c * h * w + ci * h * w + hi * w + wi] = src[ni * c + ci];
                    }
                }
            }
        }
        out
    }

    // NC(N_SPATIAL=32, C=128) → (d_olo, d_ohi) each [BH=4, N=16, KEY_DIM=32].
    // Inverse of fa2_pair_to_nchw∘nchw_to_nc.
    fn nc_to_fa2_pair(d_nc: &[f32]) -> (Vec<f32>, Vec<f32>) {
        let mut d_olo = vec![0.0f32; FA2_TENSOR_SIZE];
        let mut d_ohi = vec![0.0f32; FA2_TENSOR_SIZE];
        for b in 0..BATCH {
            for h in 0..NUM_HEADS {
                let bh = b * NUM_HEADS + h;
                for n in 0..N {
                    let nc_row  = (b * N + n) * C;
                    let fa2_row = bh * N * KEY_DIM + n * KEY_DIM;
                    for d in 0..KEY_DIM {
                        d_olo[fa2_row + d] = d_nc[nc_row + h * HEAD_DIM + d];
                        d_ohi[fa2_row + d] = d_nc[nc_row + h * HEAD_DIM + KEY_DIM + d];
                    }
                }
            }
        }
        (d_olo, d_ohi)
    }

    // Combine dQ, dK [BH=4,N=16,KEY_DIM=32] and dV NCHW [B=2,C=128,H,W]
    // → d_qkv NC (N_SPATIAL=32, QKV_H=256).
    fn combine_dqkv_to_nc(dq: &[f32], dk: &[f32], dv_nchw: &[f32]) -> Vec<f32> {
        let mut out = vec![0.0f32; N_SPATIAL * QKV_H];
        for b in 0..BATCH {
            for h in 0..NUM_HEADS {
                let bh     = b * NUM_HEADS + h;
                let q_ch   = h * HEAD_SPAN;
                let k_ch   = q_ch + KEY_DIM;
                let vlo_ch = k_ch + KEY_DIM;
                let vhi_ch = vlo_ch + KEY_DIM;
                for n in 0..N {
                    let fa2_row = bh * N * KEY_DIM + n * KEY_DIM;
                    let nc_row  = (b * N + n) * QKV_H;
                    for d in 0..KEY_DIM {
                        out[nc_row + q_ch + d] = dq[fa2_row + d];
                        out[nc_row + k_ch + d] = dk[fa2_row + d];
                        let lo_ch = h * HEAD_DIM + d;
                        let hi_ch = h * HEAD_DIM + KEY_DIM + d;
                        out[nc_row + vlo_ch + d] = dv_nchw[b * C * H * W + lo_ch * H * W + n];
                        out[nc_row + vhi_ch + d] = dv_nchw[b * C * H * W + hi_ch * H * W + n];
                    }
                }
            }
        }
        out
    }

