// C2PSA block backward-pass CUDA test.
//
// Verifies the full backward pass of C2PSA(c1=256, c2=256, n=1, e=0.5) in
// training mode by comparing the computed dx against PyTorch autograd reference.
//
// Fixtures from tests/fixtures/c2psa_yolo26/backward/ contain:
//   - x, dy, dx_expected
//   - Per-stage (×7): pre_bn_nc, bn_mean, bn_rstd, pre_silu_nc, conv_w, bn_w
//   - FA2 tensors: q, k, v_lo, v_hi, o_lo, o_hi, L
//
// Backward order:
//   cv2 SiLU↓ → cv2 BN↓ → cv2 Conv1×1 Dx
//   → cat↓ → [d_a, d_b_final]
//   → ffn shortcut: d_b_after_attn += d_b_final
//   → ffn1 BN↓ → ffn1 Conv1×1 Dx → ffn0 SiLU↓ → ffn0 BN↓ → ffn0 Conv1×1 Dx
//   → accumulate d_b_after_attn
//   → proj BN↓ → proj Conv1×1 Dx → d_x_attn
//   → pe BN↓ → pe DW Conv3×3 Dx → d_v_nchw_from_pe
//   → FA2 backward lo+hi → dQ, dK, dV
//   → combine d_qkv_bn
//   → qkv BN↓ → qkv Conv1×1 Dx → d_b_from_attn
//   → accumulate d_b
//   → chunk↓ → d_cv1_out
//   → cv1 SiLU↓ → cv1 BN↓ → cv1 Conv1×1 Dx → dx
//
// Fixtures generated by tests/fixtures/c2psa_yolo26/generate_backward.py.

